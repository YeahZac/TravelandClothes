function resolveSeedId(id) {
  const sid = String(id || '').trim()
  return SEED_ID_ALIASES[sid] || sid
}

function resolvePhaseId(id) {
  const pid = String(id || '').trim()
  return PHASE_ID_ALIASES[pid] || pid
}

