function scalePhases(nutMult = 1, dayMult = 1, perPhase) {
  return BASE_PHASES.map((p, i) => {
    const nm = perPhase && perPhase[i] ? perPhase[i].nut || nutMult : nutMult
    const dm = perPhase && perPhase[i] ? perPhase[i].day || dayMult : dayMult
    return {
      id: p.id,
      name: p.name,
      tip: p.tip,
      needNutrition: Math.round(p.needNutrition * nm),
      needDays: Math.round(p.needDays * dm),
    }
  })
}

